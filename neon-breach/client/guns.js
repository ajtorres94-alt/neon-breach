// Weapon models built from rounded boxes (B), tubes (T) and ellipsoids (E), each modelled after its real-world counterpart.
// Weapon space (metres): +x right, +y up, -z forward (the muzzle). The origin is at the trigger hand.
// Colour keys: m metal, d dark steel, p polymer, w wood, g gold, a weapon accent colour, l lens, r red dot; or an [r,g,b] array.
// Used by the first-person view, the third-person soldiers and the showcase test.

const B = (x, y, z, sx, sy, sz, c, r, pt = 0, rl = 0) => ({ k: 'b', x, y, z, sx, sy, sz, c, r, pt, rl });
const T = (x0, y0, z0, x1, y1, z1, r, c, r1) => ({ k: 't', x0, y0, z0, x1, y1, z1, r, c, r1: r1 ?? r });
const E = (x, y, z, rx, ry, rz, c) => ({ k: 'e', x, y, z, rx, ry, rz, c });

/** Curved magazine: a chain of tilted boxes from (x, ytop, ztop) curving towards -z (like an AK or MP5 mag). */
function mag(c, x, ytop, ztop, len, w, d, curve, n = 5) {
  const out = []; let y = ytop, z = ztop; const L = len / n;
  for (let i = 0; i < n; i++) {
    const a = curve * (i + 0.5) / n, dy = -Math.cos(a) * L, dz = -Math.sin(a) * L;
    out.push(B(x, y + dy / 2, z + dz / 2, w, L * 1.06, d, c, 0.006, a)); y += dy; z += dz;
  }
  out.push(B(x, y - 0.004, z - 0.002, w + 0.004, 0.008, d + 0.004, 'd', 0.003, curve));
  return out;
}
