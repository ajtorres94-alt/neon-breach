const TEX_ORDER = ['gunmetal', 'polymer', 'gunwood', 'plain'];
const texOf = (c, gold) => (gold ? 'plain' : Array.isArray(c) ? 'polymer' : c === 'm' || c === 'd' ? 'gunmetal' : c === 'p' ? 'polymer' : c === 'w' ? 'gunwood' : 'plain');
const specOf = (c, gold) => (gold ? 1.1 : Array.isArray(c) ? 0.3 : c === 'l' ? 1.2 : c === 'a' ? 0.15 : c === 'p' ? 0.3 : c === 'w' ? 0.25 : 0.7);
const emitOf = (c, gold) => (gold ? 0.3 : c === 'l' ? 0.1 : c === 'r' ? 0.8 : 0);
const colOf = (c, accent, gold) => (gold ? GUN_COL.g : Array.isArray(c) ? c : c === 'a' ? accent.map(v => v * 0.38) : GUN_COL[c] || GUN_COL.m);

/** Draw a gun. o.pos(x,y,z) maps weapon space to world/view space; o.yaw / o.pitch rotate the boxes to match. */
export function drawGun(R, gun, o) {
  const { pos, yaw = 0, pitch = 0, accent = [0.5, 0.5, 0.5] } = o, gold = !!gun.gold || !!o.gold;
  for (const tex of TEX_ORDER) {
    let started = false;
    for (const p of gun.parts) {
      if (texOf(p.c, gold) !== tex) continue;
      if (!started) { R.texture(tex, 1); started = true; }
      const col = colOf(p.c, accent, gold), em = emitOf(p.c, gold), sp = specOf(p.c, gold);
      if (p.k === 't') { const e0 = pos(p.x0, p.y0, p.z0), e1 = pos(p.x1, p.y1, p.z1); R.tube(e0[0], e0[1], e0[2], e1[0], e1[1], e1[2], p.r, p.r1, col, sp, em); }
      else if (p.k === 'e') { const c = pos(p.x, p.y, p.z); R.sphere(c[0], c[1], c[2], p.rx, p.ry, p.rz, col, em, 1, sp, yaw, pitch); }
      else { const c = pos(p.x, p.y, p.z); R.rbox(c[0], c[1], c[2], p.sx, p.sy, p.sz, yaw, pitch + p.pt, col, p.r ?? Math.min(p.sx, p.sy, p.sz) * 0.3, em, 1, sp, p.rl); }
    }
  }
  R.texture('plain');
}
